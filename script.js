function getRandomPhrase() {
    let index;
    do {
        index = Math.floor(Math.random() * allPhrases.length);
    } while (index === lastIndex && allPhrases.length > 1);
    lastIndex = index;
    return allPhrases[index];
}

function updateCategoryBadge(categoryKey) {
    const data = phrasesData[categoryKey];
    const colors = categoryColors[categoryKey];
    categoryBadge.textContent = data.name;
    categoryBadge.style.background = colors.bg;
    categoryBadge.style.borderColor = colors.border;
    categoryBadge.style.color = colors.color;
}

function generatePhrase() {
    if (isAnimating) return;
    isAnimating = true;

    phraseEl.classList.remove('fade-in');
    phraseEl.classList.add('fade-out');

    setTimeout(() => {
        const item = getRandomPhrase();
        phraseEl.textContent = item.text;
        updateCategoryBadge(item.category);

        phraseEl.classList.remove('fade-out');
        phraseEl.classList.add('fade-in');

        counter++;
        counterEl.textContent = counter;

        setTimeout(() => {
            isAnimating = false;
        }, 300);
    }, 400);
}

generateBtn.addEventListener('click', generatePhrase);

window.addEventListener('load', () => {
    setTimeout(() => {
        const item = getRandomPhrase();
        phraseEl.textContent = item.text;
        updateCategoryBadge(item.category);
        phraseEl.classList.add('fade-in');
        counter = 1;
        counterEl.textContent = counter;
    }, 800);
});

document.addEventListener('keydown', (e) => {
    if (e.code === 'Space' && document.activeElement !== generateBtn) {
        e.preventDefault();
        generatePhrase();
    }
});